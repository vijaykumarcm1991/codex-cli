"""Shareable single-file HTML transcript export for saved sessions."""
from __future__ import annotations

import html
import json
import re
from datetime import datetime, timezone
from pathlib import Path


def _md_to_html(text: str) -> str:
    """Minimal, escaped markdown-to-HTML: fences, headings, lists, bold, code, links."""
    escaped = html.escape(text)

    def fence(match: re.Match) -> str:
        language = match.group(1) or ""
        return f'</p><pre><code class="lang-{html.escape(language)}">{match.group(2)}</code></pre><p>'

    escaped = re.sub(r"```([\w+-]*)\n(.*?)```", fence, escaped, flags=re.DOTALL)
    escaped = re.sub(r"^#{1,6}\s+(.+)$", r"<strong>\1</strong>", escaped, flags=re.MULTILINE)
    escaped = re.sub(r"^- (.+)$", r"&bull; \1", escaped, flags=re.MULTILINE)
    escaped = re.sub(r"`([^`\n]+)`", r"<code>\1</code>", escaped)
    escaped = re.sub(r"\*\*([^*\n]+)\*\*", r"<strong>\1</strong>", escaped)
    escaped = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2">\1</a>', escaped)
    return escaped


def session_to_html(data: dict, model_id: str = "") -> str:
    """Build a standalone dark-theme HTML page from one saved session record."""
    messages = data.get("messages", [])
    blocks = []
    for message in messages:
        role = message.get("role")
        if role == "user":
            content = message.get("content")
            if isinstance(content, list):  # image attachments
                parts = [p.get("text", "") for p in content if isinstance(p, dict) and p.get("type") == "text"]
                content = " ".join(parts) + " 🖼️"
            blocks.append(f'<div class="msg user"><div class="who">you</div><p>{_md_to_html(str(content))}</p></div>')
        elif role == "assistant":
            body = str(message.get("content") or "")
            calls = ""
            for call in message.get("tool_calls", []):
                fn = call.get("function", {})
                try:
                    args = json.dumps(json.loads(fn.get("arguments", "{}")), ensure_ascii=False)
                except ValueError:
                    args = fn.get("arguments", "")
                calls += (f'<details class="tool"><summary>tool · {html.escape(str(fn.get("name", "?")))}</summary>'
                          f'<pre>{html.escape(args[:4000])}</pre></details>')
            if body or calls:
                blocks.append(f'<div class="msg agent"><div class="who">oac</div>'
                              f'<p>{_md_to_html(body)}</p>{calls}</div>')
        elif role == "tool":
            blocks.append(f'<div class="msg tool"><div class="who">result</div>'
                          f'<pre>{html.escape(str(message.get("content", ""))[:4000])}</pre></div>')
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    title = html.escape(data.get("title") or data.get("id", "session"))
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>oac · {title}</title>
<style>
:root {{ color-scheme: dark; }}
body {{ margin: 0; background: #16161e; color: #c0caf5;
  font: 15px/1.6 -apple-system, "Segoe UI", Roboto, "Noto Sans", sans-serif; }}
header {{ padding: 28px 20px 10px; max-width: 860px; margin: 0 auto; }}
header h1 {{ font-size: 20px; color: #7aa2f7; margin: 0 0 4px; }}
header p {{ color: #565f89; margin: 2px 0; font-size: 13px; }}
main {{ max-width: 860px; margin: 0 auto; padding: 10px 20px 60px; }}
.msg {{ border-radius: 10px; padding: 12px 16px; margin: 14px 0; }}
.msg p {{ margin: 6px 0; white-space: pre-wrap; overflow-wrap: anywhere; }}
.user {{ background: #1f2335; border-left: 3px solid #7aa2f7; }}
.agent {{ background: #1a1b26; border-left: 3px solid #9ece6a; }}
.tool {{ background: #181824; border-left: 3px solid #e0af68; }}
.who {{ font-size: 11px; letter-spacing: 2px; text-transform: uppercase; color: #565f89; }}
.user .who {{ color: #7aa2f7; }} .agent .who {{ color: #9ece6a; }} .tool .who {{ color: #e0af68; }}
pre {{ background: #101017; border: 1px solid #2a2b3d; border-radius: 8px;
  padding: 10px 12px; overflow-x: auto; font-size: 12.5px; color: #a9b1d6; }}
code {{ font-family: ui-monospace, "Cascadia Code", Consolas, monospace; }}
p code {{ background: #101017; padding: 1px 5px; border-radius: 4px; color: #bb9af7; }}
a {{ color: #7dcfff; }}
details {{ margin: 6px 0; }} summary {{ cursor: pointer; color: #e0af68; font-size: 12.5px; }}
footer {{ text-align: center; color: #565f89; font-size: 12px; padding: 20px; }}
</style></head><body>
<header><h1>{title}</h1>
<p>session {html.escape(str(data.get('id', '?')))} · model {html.escape(str(data.get('model') or model_id or '?'))}</p>
<p>exported {generated} · generated by oac</p></header>
<main>{''.join(blocks) or '<p class="msg">(empty session)</p>'}</main>
<footer>exported from oac — the zero-dependency terminal coding agent</footer>
</body></html>"""


def export_session_file(data: dict, path: Path, model_id: str = "") -> Path:
    path.write_text(session_to_html(data, model_id), encoding="utf-8")
    return path
